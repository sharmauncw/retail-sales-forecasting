"""Build the analytics mart with DuckDB.

Executes sql/build_mart.sql, persists the marts to
outputs/retail_mart.duckdb, and writes outputs/mart_summary.md with
row counts plus sample rows.

Usage:
    python sql/run_mart.py
(run from the repo root)
"""

from __future__ import annotations

from pathlib import Path

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SQL = ROOT / "sql" / "build_mart.sql"
DB = ROOT / "outputs" / "retail_mart.duckdb"
SUMMARY = ROOT / "outputs" / "mart_summary.md"

MARTS = ["mart_daily_sales", "mart_store_category_monthly", "mart_promo_lift"]


def main() -> None:
    ROOT.joinpath("outputs").mkdir(parents=True, exist_ok=True)
    if DB.exists():
        DB.unlink()

    con = duckdb.connect(str(DB))
    try:
        con.execute(SQL.read_text())
    finally:
        con.close()

    con = duckdb.connect(str(DB), read_only=True)
    try:
        counts = {t: con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
                  for t in MARTS}
        samples = {t: con.execute(f"SELECT * FROM {t} LIMIT 5").df()
                   for t in MARTS}
    finally:
        con.close()

    lines = [
        "# Retail mart summary (DuckDB)",
        "",
        "Built from `data/retail_sales_daily.csv` — **synthetic data**, generated by",
        "`data/generate_data.py` (seed 42). Marts persisted in",
        "`outputs/retail_mart.duckdb`.",
        "",
        "## Row counts",
        "",
        "| mart | rows |",
        "| --- | ---: |",
    ]
    for t in MARTS:
        lines.append(f"| `{t}` | {counts[t]:,} |")
    lines += ["", "## Sample rows", ""]
    for t in MARTS:
        lines.append(f"### `{t}`")
        lines.append("")
        lines.append(samples[t].to_markdown(index=False))
        lines.append("")
    SUMMARY.write_text("\n".join(lines))

    print(f"Persisted marts to {DB} ({DB.stat().st_size / 1024:,.0f} KB)")
    for t, n in counts.items():
        print(f"  {t}: {n:,} rows")
    print(f"Wrote {SUMMARY}")


if __name__ == "__main__":
    main()
